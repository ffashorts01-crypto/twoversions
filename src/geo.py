ENTRIES = []
for _l in _RAW.strip().splitlines():
    if not _l.strip() or _l.startswith('#'): continue
    _p, _la, _lo = _l.rsplit('|', 2)
    ENTRIES.append((re.compile(r'(?<![А-Яа-яЁё])(?:' + _p + ')'), float(_la), float(_lo), _p))

def _first(text):
    best = None
    for rx, la, lo, key in ENTRIES:
        m = rx.search(text or '')
        if not m: continue
        rank = (m.start(), -(m.end() - m.start()))
        if best is None or rank < best[0]: best = (rank, la, lo, key)
    return best

def locate(place, title=''):
    """(lat, lon, key) of the first known place named in the card's `place`, else in its title; None when nothing on the table
    is named (country-wide events such as «Украина» are not put on the map). For pairs such as «Вашингтон — Киев» only the
    first part counts, so diplomacy in Washington is not drawn in Kyiv."""
    pl = place or ''
    parts = re.split(r' [—–/] | / |/', pl)
    if len(parts) > 1:
        b = _first(parts[0])
        return (b[1], b[2], b[3]) if b else None
    b = _first(pl) or _first(title)
    return (b[1], b[2], b[3]) if b else None
